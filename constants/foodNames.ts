// WHY THIS EXISTS. Both nutrition APIs match WHOLE WORDS. Typing "broc"
// returns nothing from either of them, because "broc" isn't a word in
// "Broccoli, raw" — you have to spell the whole thing before anything appears.
// That's a miserable way to search, and it reads as the app being broken
// rather than the database being strict.
//
// So this list sits in front: "broc" matches "broccoli" HERE, instantly and
// offline, and the full word is what gets sent to the API. The user types
// three letters; the network sees a word it can actually match.
//
// CURATED, not scraped. A list of every food in existence would make the
// prefix match noisier than no match at all — twenty thousand entries means
// "chi" returns four hundred things nobody was looking for. These are the
// foods people actually log, including West African dishes that most
// nutrition apps ignore entirely.
//
// Anything NOT in this list still works — it just needs the full word, which
// is exactly how the search behaved before this file existed. Adding a name
// here can only ever help.

