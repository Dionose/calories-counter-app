/** Names starting with what's been typed so far.
    Prefix, not substring: "rice" should suggest "rice noodles", not every
    food with "rice" buried in the middle. Someone typing the start of a word
    means the start of a word. */
export function prefixMatches(query: string, limit = 6): string[] {
  const q = query.trim().toLowerCase();
  if (q.length < 2) return [];

  const starts: string[] = [];
  const wordStarts: string[] = [];

  for (const name of FOOD_NAMES) {
    if (name.startsWith(q)) {
      starts.push(name);
      continue;
    }
    /* also match the start of any LATER word, so "chick" finds "grilled
       chicken" — people don't always begin with the first word of a dish */
    if (name.split(" ").slice(1).some((w) => w.startsWith(q))) {
      wordStarts.push(name);
    }
  }

  /* names that START with the query rank above ones that merely contain a
     matching word — "ric" should offer "rice" before "fried rice" */
  return [...starts, ...wordStarts].slice(0, limit);
}
